# ============================================================
# 6. 多变量赋值与交换
# ============================================================

x, y = 1, 2
print(f"交换前: x={x}, y={y}")
x, y = y, x                          # Python 特性：一行交换两个变量
print(f"交换后: x={x}, y={y}")


