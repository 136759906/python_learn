# ============================================================
# 1. 变量：Python 不需要声明类型，直接赋值即可
# ============================================================

name = "张三"          # str  字符串
age = 28               # int  整数
height = 1.75          # float 浮点数
is_student = False     # bool 布尔值（True / False）

print("姓名:", name)
print("年龄:", age)
print("身高:", height)
print("是否学生:", is_student)

# type() 可以查看变量类型
print("name 的类型:", type(name))
print("age 的类型:", type(age))

# ============================================================
# 2. f-string：Python 中最推荐的字符串格式化方式
# ============================================================

print(f"{name} 今年 {age} 岁，身高 {height} 米。")

# 保留小数位
print(f"身高保留两位小数: {height:.2f}")

# ============================================================
# 3. 基本运算
# ============================================================

a = 10
b = 3

print(f"{a} + {b} = {a + b}")     # 加
print(f"{a} - {b} = {a - b}")     # 减
print(f"{a} * {b} = {a * b}")     # 乘
print(f"{a} / {b} = {a / b}")     # 除（结果是 float）
print(f"{a} // {b} = {a // b}")   # 整除（只留整数部分）
print(f"{a} % {b} = {a % b}")     # 取余数
print(f"{a} ** {b} = {a ** b}")   # 幂运算（10 的 3 次方）

# ============================================================
# 4. 类型转换
# ============================================================

text_number = "42"
real_number = int(text_number)      # str -> int
print(f'"42" 转成整数后加 1: {real_number + 1}')

price_text = str(99.5)              # float -> str
print(f'99.5 转成字符串后拼接 "元": {price_text}元')

